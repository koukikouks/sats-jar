/** The SDK's refusal for `code`, with its readable message. */
export function refusal(code: RefusalCode, explorerUrl: string | null = null): SatsJarRefusal {
  return new SatsJarRefusal(code, MESSAGES[code], explorerUrl);
}

/** A contract code this SDK knows, or null (then the caller says REFUSED). */
export function knownCode(code: string): RefusalCode | null {
  return Object.hasOwn(MESSAGES, code) ? (code as RefusalCode) : null;
}

/** Network and upstream failures, never with their raw text. */
export const unavailable = (): SatsJarRefusal => refusal("UNAVAILABLE");
